"""Generate the shared Micro UI font manifest and platform assets."""

from __future__ import annotations

import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import subprocess
import sys
import tempfile


REPOSITORY_ROOT = Path(__file__).resolve().parents[1]
FONT_DIRECTORY = REPOSITORY_ROOT / "assets/fonts"
MANIFEST_PATH = FONT_DIRECTORY / "ui-sans-common.txt"
METADATA_PATH = FONT_DIRECTORY / "noto-sans-sc.json"
LICENSE_PATH = FONT_DIRECTORY / "OFL-1.1.txt"
SOURCE_PATH = REPOSITORY_ROOT / "work/fonts/NotoSansCJKsc-Regular.otf"
IPA_SOURCE_PATH = REPOSITORY_ROOT / "work/fonts/NotoSans-Regular.otf"
PYTHON_TOOLS = REPOSITORY_ROOT / "work/tools/python"
LV_FONT_CONV = (
    REPOSITORY_ROOT / "work/tools/lv-font-conv/node_modules/.bin/lv_font_conv"
)
WEB_FONT_PATH = (
    REPOSITORY_ROOT
    / "products/micro-web-player/public/fonts/micro-ui-sans-common.woff2"
)
IPA_WEB_FONT_PATH = (
    REPOSITORY_ROOT
    / "products/micro-web-player/public/fonts/micro-ui-ipa.woff2"
)
LVGL_DIRECTORY = FONT_DIRECTORY / "lvgl"
LVGL_SIZES_PATH = LVGL_DIRECTORY / "micro_ui_sans_sizes.json"
LV_FONT_CONV_LOCK = FONT_DIRECTORY / "lv-font-conv-lock.json"
INSTALLED_LV_FONT_CONV_LOCK = REPOSITORY_ROOT / "work/tools/lv-font-conv/node_modules/.package-lock.json"
FONT_SIZES = (12, 14, 18, 24, 32)
FONT_METRICS = {12: 14, 14: 18, 18: 24, 24: 32, 32: 40}
LVGL_BPP = 2
CHINESE_PUNCTUATION = tuple(
    "·—‘’“”…、。〈〉《》「」『』【】〔〕！（），．：；？"
)
# The IPA supplement covers the complete IPA Extensions and Spacing Modifier
# Letters blocks, combining diacritics used by narrow transcriptions, and the
# Latin/Greek letters that dictionaries borrow for phonemic notation.
IPA_RANGES = ((0x0250, 0x02AF), (0x02B0, 0x02FF), (0x0300, 0x036F))
IPA_EXTRA_GLYPHS = "æÆðÐøØþÞßçÇħĦŋŊıİǀǁǂǃβγδθφχ‿↗↘→ǝɁɂ"
# Noto Sans CJK SC already owns the tone arrows; the Noto Sans supplement does
# not, so they stay in the primary LVGL/Web asset instead of the fallback.
IPA_PRIMARY_GLYPHS = "↗↘→"


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as source:
        for chunk in iter(lambda: source.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def gb2312_level_one_han() -> tuple[str, ...]:
    glyphs: list[str] = []
    for lead in range(0xB0, 0xD8):
        for trail in range(0xA1, 0xFF):
            try:
                glyph = bytes((lead, trail)).decode("gb2312")
            except UnicodeDecodeError:
                continue
            if len(glyph) == 1 and "\u4e00" <= glyph <= "\u9fff":
                glyphs.append(glyph)
    unique = tuple(sorted(set(glyphs), key=ord))
    if len(glyphs) != 3755 or len(unique) != 3755:
        raise RuntimeError(
            f"expected 3755 unique GB2312 level-1 Han glyphs, "
            f"found {len(glyphs)} ({len(unique)} unique)"
        )
    return unique


def base_font_glyphs() -> tuple[str, ...]:
    ascii_glyphs = tuple(chr(codepoint) for codepoint in range(0x20, 0x7F))
    punctuation = tuple(sorted(set(CHINESE_PUNCTUATION), key=ord))
    primary_ipa = tuple(sorted(set(IPA_PRIMARY_GLYPHS), key=ord))
    han = gb2312_level_one_han()
    glyphs = ascii_glyphs + punctuation + ("\ufffd",) + primary_ipa + han
    if len(set(glyphs)) != len(glyphs):
        raise RuntimeError("primary font glyph groups overlap")
    return glyphs


def ipa_glyphs() -> tuple[str, ...]:
    glyphs = {
        chr(codepoint)
        for start, end in IPA_RANGES
        for codepoint in range(start, end + 1)
    }
    glyphs.update(IPA_EXTRA_GLYPHS)
    return tuple(sorted(glyphs, key=ord))


def ipa_supplement_glyphs() -> tuple[str, ...]:
    excluded = set(IPA_PRIMARY_GLYPHS)
    return tuple(glyph for glyph in ipa_glyphs() if glyph not in excluded)


def manifest_glyphs() -> tuple[str, ...]:
    ascii_glyphs = tuple(chr(codepoint) for codepoint in range(0x20, 0x7F))
    punctuation = tuple(sorted(set(CHINESE_PUNCTUATION), key=ord))
    glyphs = ascii_glyphs + punctuation + ("\ufffd",) + ipa_glyphs() + gb2312_level_one_han()
    if len(set(glyphs)) != len(glyphs):
        raise RuntimeError("font manifest glyph groups overlap")
    return glyphs


def manifest_bytes() -> bytes:
    header = (
        "# Generated by scripts/generate-font-assets.py; do not edit.\n"
        "# Printable ASCII U+0020-U+007E and common Chinese punctuation, then\n"
        "# U+FFFD replacement, then IPA Extensions/Spacing Modifiers/Combining\n"
        "# Diacritics plus phonetic Latin/Greek letters, then exactly 3755 GB2312\n"
        "# level-1 Han glyphs in Unicode order.\n"
    )
    ascii_line = "".join(chr(codepoint) for codepoint in range(0x20, 0x7F))
    punctuation_line = "".join(sorted(set(CHINESE_PUNCTUATION), key=ord))
    ipa_line = "".join(ipa_glyphs())
    han_lines = "".join(f"{glyph}\n" for glyph in gb2312_level_one_han())
    return (
        header
        + f"{ascii_line}\n{punctuation_line}\n�\n{ipa_line}\n{han_lines}"
    ).encode()


def generate_manifest(check: bool) -> None:
    expected = manifest_bytes()
    if check:
        if not MANIFEST_PATH.is_file() or MANIFEST_PATH.read_bytes() != expected:
            raise SystemExit(
                f"{MANIFEST_PATH.relative_to(REPOSITORY_ROOT)} differs from generated output"
            )
        return
    MANIFEST_PATH.parent.mkdir(parents=True, exist_ok=True)
    MANIFEST_PATH.write_bytes(expected)


def load_metadata() -> dict[str, object]:
    metadata = json.loads(METADATA_PATH.read_text(encoding="utf-8"))
    if metadata["source_sha256"] != sha256(SOURCE_PATH):
        raise SystemExit(
            f"{SOURCE_PATH.relative_to(REPOSITORY_ROOT)} does not match pinned SHA-256"
        )
    if metadata["license_sha256"] != sha256(LICENSE_PATH):
        raise SystemExit("tracked SIL OFL text does not match pinned SHA-256")
    ipa = metadata.get("ipa")
    if not isinstance(ipa, dict):
        raise SystemExit("font metadata lacks the IPA supplement source")
    if ipa["source_sha256"] != sha256(IPA_SOURCE_PATH):
        raise SystemExit(
            f"{IPA_SOURCE_PATH.relative_to(REPOSITORY_ROOT)} does not match pinned SHA-256"
        )
    ipa_license = REPOSITORY_ROOT / str(ipa["license_file"])
    if ipa["license_sha256"] != sha256(ipa_license):
        raise SystemExit("tracked Noto Sans OFL text does not match pinned SHA-256")
    return metadata


def tool_environment() -> dict[str, str]:
    environment = os.environ.copy()
    existing = environment.get("PYTHONPATH")
    environment["PYTHONPATH"] = (
        str(PYTHON_TOOLS) if not existing else f"{PYTHON_TOOLS}{os.pathsep}{existing}"
    )
    return environment


def verify_tools(metadata: dict[str, object]) -> dict[str, str]:
    tools = metadata["generation_tools"]
    assert isinstance(tools, dict)
    if (
        not PYTHON_TOOLS.is_dir()
        or not LV_FONT_CONV.is_file()
        or not INSTALLED_LV_FONT_CONV_LOCK.is_file()
    ):
        raise SystemExit(
            "missing repository-local generators under work/tools; "
            "see assets/fonts/README.md"
        )
    environment = tool_environment()
    fonttools_version = subprocess.run(
        [sys.executable, "-c", "import fontTools; print(fontTools.__version__)"],
        check=True,
        capture_output=True,
        text=True,
        env=environment,
    ).stdout.strip()
    brotli_version = subprocess.run(
        [sys.executable, "-c", "import brotli; print(brotli.__version__)"],
        check=True, capture_output=True, text=True, env=environment,
    ).stdout.strip()
    lv_version = subprocess.run(
        [str(LV_FONT_CONV), "--version"],
        check=True,
        capture_output=True,
        text=True,
    ).stdout.strip()
    if fonttools_version != tools["fonttools"]:
        raise SystemExit(
            f"fontTools {fonttools_version} is installed; expected {tools['fonttools']}"
        )
    if brotli_version != tools["brotli"]:
        raise SystemExit(f"Brotli {brotli_version} is installed; expected {tools['brotli']}")
    if lv_version != tools["lv_font_conv"]:
        raise SystemExit(
            f"lv_font_conv {lv_version} is installed; expected {tools['lv_font_conv']}"
        )
    expected_lock = json.loads(LV_FONT_CONV_LOCK.read_text(encoding="utf-8"))
    installed_lock = json.loads(INSTALLED_LV_FONT_CONV_LOCK.read_text(encoding="utf-8"))
    if installed_lock != expected_lock:
        raise SystemExit("repository-local lv_font_conv dependency tree differs from tracked lock")
    return environment


def run(command: list[str], *, environment: dict[str, str] | None = None) -> None:
    subprocess.run(command, check=True, env=environment)


def normalize_lvgl_c(
    contents: bytes,
    payload_bytes: int,
    line_height_px: int,
    *,
    symbol_prefix: str,
    export_macro: str,
    source_label: str,
    base_line_px: int | None = None,
    fallback_symbol: str | None = None,
) -> bytes:
    text = contents.decode().replace("\r\n", "\n")
    text, replacements = re.subn(
        r"^ \* Opts: .*\n",
        f" * Source: {source_label}\n",
        text,
        count=1,
        flags=re.MULTILINE,
    )
    if replacements != 1:
        raise RuntimeError("lv_font_conv output did not contain its expected options line")
    symbol = re.search(
        rf"^const lv_font_t ({re.escape(symbol_prefix)}_\d+) =", text, re.MULTILINE
    )
    if symbol is None:
        raise RuntimeError("lv_font_conv output did not contain its expected public font symbol")
    text, line_height_replacements = re.subn(
        r"(\.line_height = )\d+(,)",
        rf"\g<1>{line_height_px}\g<2>",
        text,
        count=1,
    )
    if line_height_replacements != 1:
        raise RuntimeError("lv_font_conv output did not contain one font line height")
    if base_line_px is not None:
        text, base_line_replacements = re.subn(
            r"(\.base_line = )-?\d+(,)",
            rf"\g<1>{base_line_px}\g<2>",
            text,
            count=1,
        )
        if base_line_replacements != 1:
            raise RuntimeError("lv_font_conv output did not contain one font base line")
    if fallback_symbol is not None:
        marker = "/*Initialize a public general font descriptor*/\n"
        if marker not in text:
            raise RuntimeError("lv_font_conv output did not contain its public font comment")
        text = text.replace(
            marker,
            f"extern const lv_font_t {fallback_symbol};\n\n{marker}",
            1,
        )
        text, fallback_replacements = re.subn(
            r"\.fallback = NULL,",
            f".fallback = &{fallback_symbol},",
            text,
            count=1,
        )
        if fallback_replacements != 1:
            raise RuntimeError("lv_font_conv output did not contain one fallback field")
    text = text.replace(
        f"const lv_font_t {symbol.group(1)} =",
        f"{export_macro} const lv_font_t {symbol.group(1)} =",
        1,
    )
    declaration = (
        f"/* Generated from {source_label}; do not edit.\n"
        f" * MICRO_UI_FONT_PAYLOAD_BYTES {payload_bytes}\n"
        " * SPDX-License-Identifier: OFL-1.1\n"
        " */\n"
        "#if defined(_WIN32)\n"
        f"#define {export_macro} __declspec(dllexport)\n"
        "#elif defined(__GNUC__)\n"
        f'#define {export_macro} __attribute__((visibility("default")))\n'
        "#else\n"
        f"#define {export_macro}\n"
        "#endif\n"
    )
    return (declaration + text.rstrip() + "\n").encode()


def derive_generation_font(destination: Path, environment: dict[str, str]) -> None:
    """Add U+FFFD as an alias of the pinned source's U+25A1 glyph."""
    script = """
import sys
from fontTools.ttLib import TTFont
font = TTFont(sys.argv[1], recalcTimestamp=False)
mapped = 0
for table in font['cmap'].tables:
    if table.isUnicode() and 0x25A1 in table.cmap:
        table.cmap[0xFFFD] = table.cmap[0x25A1]
        mapped += 1
if not mapped:
    raise SystemExit('pinned source lacks U+25A1 replacement outline')
font.save(sys.argv[2], reorderTables=True)
"""
    run([sys.executable, "-c", script, str(SOURCE_PATH), str(destination)], environment=environment)


def generate_web_font(
    source: Path, destination: Path, glyph_text: Path, environment: dict[str, str]
) -> None:
    run(
        [
            sys.executable,
            "-m",
            "fontTools.subset",
            str(source),
            f"--output-file={destination}",
            "--flavor=woff2",
            f"--text-file={glyph_text}",
            "--layout-features=",
            "--no-hinting",
            "--no-recalc-timestamp",
            "--canonical-order",
            "--name-IDs=0,1,2,3,4,5,6",
            "--name-languages=0x409,0x804",
        ],
        environment=environment,
    )


def verify_web_glyph(
    font: Path, codepoint: int, label: str, environment: dict[str, str]
) -> None:
    script = """
import sys
from fontTools.ttLib import TTFont
font = TTFont(sys.argv[1])
codepoint = int(sys.argv[2], 16)
if not any(codepoint in table.cmap for table in font['cmap'].tables if table.isUnicode()):
    raise SystemExit(f'generated Web font lacks {sys.argv[3]}')
"""
    run(
        [sys.executable, "-c", script, str(font), f"{codepoint:04X}", label],
        environment=environment,
    )


def verify_source_glyphs(
    source: Path, glyphs: tuple[str, ...], label: str, environment: dict[str, str]
) -> None:
    script = """
import sys
from fontTools.ttLib import TTFont
font = TTFont(sys.argv[1])
cmap = set()
for table in font['cmap'].tables:
    if table.isUnicode():
        cmap.update(table.cmap)
missing = [glyph for glyph in sys.argv[2] if ord(glyph) not in cmap]
if missing:
    formatted = ', '.join(f'U+{ord(glyph):04X}' for glyph in missing[:16])
    raise SystemExit(f'{sys.argv[3]} lacks: {formatted}')
"""
    run(
        [sys.executable, "-c", script, str(source), "".join(glyphs), label],
        environment=environment,
    )


def lvgl_font_contains(contents: str, codepoint: int) -> bool:
    lists = {
        name: [int(value, 16) for value in re.findall(r"0x([0-9a-fA-F]+)", values)]
        for name, values in re.findall(
            r"static const uint16_t (unicode_list_\d+)\[\] =\s*\{(.*?)\};",
            contents,
            re.DOTALL,
        )
    }
    for block in re.findall(r"\{\s*\.range_start.*?\}", contents, re.DOTALL):
        start = re.search(r"\.range_start = (\d+)", block)
        length = re.search(r"\.range_length = (\d+)", block)
        unicode_list = re.search(r"\.unicode_list = ([A-Za-z0-9_]+)", block)
        if start is None or length is None or unicode_list is None:
            continue
        offset = codepoint - int(start.group(1))
        if not 0 <= offset < int(length.group(1)):
            continue
        name = unicode_list.group(1)
        if name == "NULL" or offset in lists.get(name, []):
            return True
    return False


def generate_lvgl_font(
    source: Path,
    size: int,
    c_destination: Path,
    bin_destination: Path,
    glyphs: str,
    font_name: str,
) -> None:
    common = [
        str(LV_FONT_CONV),
        "--size",
        str(size),
        "--bpp",
        str(LVGL_BPP),
        "--font",
        str(source),
        "--symbols",
        glyphs,
        "--no-kerning",
        "--lv-font-name",
        font_name,
    ]
    run(
        common
        + ["--format", "lvgl", "--lv-include", "lvgl.h", "-o", str(c_destination)]
    )
    run(common + ["--format", "bin", "-o", str(bin_destination)])


def generate_fonts(check: bool) -> None:
    generate_manifest(check=check)
    metadata = load_metadata()
    if (
        metadata.get("lvgl_bpp") != LVGL_BPP
        or metadata.get("sizes_px") != list(FONT_SIZES)
        or metadata.get("line_heights_px") != [FONT_METRICS[size] for size in FONT_SIZES]
    ):
        raise SystemExit("font metadata differs from generated LVGL metrics")
    environment = verify_tools(metadata)
    base_glyphs = base_font_glyphs()
    supplement_glyphs = ipa_supplement_glyphs()
    manifest = set(manifest_glyphs())
    covered = set(base_glyphs) | set(supplement_glyphs)
    uncovered = sorted(manifest - covered, key=ord)
    if uncovered:
        formatted = ", ".join(f"U+{ord(glyph):04X}" for glyph in uncovered[:16])
        raise SystemExit(f"font manifest glyphs lack a generated asset: {formatted}")
    verify_source_glyphs(
        SOURCE_PATH,
        tuple(glyph for glyph in base_glyphs if glyph != "\ufffd"),
        "Noto Sans CJK SC",
        environment,
    )
    verify_source_glyphs(
        IPA_SOURCE_PATH, supplement_glyphs, "Noto Sans", environment
    )
    glyphs = "".join(base_glyphs)
    ipa_glyphs_text = "".join(supplement_glyphs)
    work_parent = REPOSITORY_ROOT / "work/fonts"
    work_parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix="micro-ui-sans-", dir=work_parent) as temporary:
        temporary_directory = Path(temporary)
        glyph_text = temporary_directory / "glyphs.txt"
        glyph_text.write_text(glyphs, encoding="utf-8")
        ipa_glyph_text = temporary_directory / "ipa-glyphs.txt"
        ipa_glyph_text.write_text(ipa_glyphs_text, encoding="utf-8")
        generation_font = temporary_directory / "NotoSansCJKsc-Regular-with-replacement.otf"
        derive_generation_font(generation_font, environment)
        web_font = temporary_directory / WEB_FONT_PATH.name
        generate_web_font(generation_font, web_font, glyph_text, environment)
        verify_web_glyph(web_font, 0xFFFD, "U+FFFD", environment)
        ipa_web_font = temporary_directory / IPA_WEB_FONT_PATH.name
        generate_web_font(IPA_SOURCE_PATH, ipa_web_font, ipa_glyph_text, environment)
        verify_web_glyph(ipa_web_font, 0x0259, "U+0259", environment)

        fonts: list[dict[str, object]] = []
        ipa_fonts: list[dict[str, object]] = []
        generated_c: dict[int, bytes] = {}
        generated_ipa_c: dict[int, bytes] = {}
        for size in FONT_SIZES:
            line_height_px = FONT_METRICS[size]
            c_font = temporary_directory / f"micro_ui_sans_{size}.c"
            bin_font = temporary_directory / f"micro_ui_sans_{size}.bin"
            generate_lvgl_font(
                generation_font,
                size,
                c_font,
                bin_font,
                glyphs,
                f"micro_ui_sans_{size}",
            )
            if not lvgl_font_contains(c_font.read_text(), ord("\ufffd")):
                raise RuntimeError(f"generated {size}px LVGL font lacks U+FFFD")
            payload_bytes = bin_font.stat().st_size
            contents = normalize_lvgl_c(
                c_font.read_bytes(),
                payload_bytes,
                line_height_px,
                symbol_prefix="micro_ui_sans",
                export_macro="MICRO_UI_SANS_EXPORT",
                source_label=(
                    "NotoSansCJKsc-Regular.otf "
                    "(pinned in assets/fonts/noto-sans-sc.json)"
                ),
                fallback_symbol=f"micro_ui_ipa_{size}",
            )
            base_line = re.search(rb"\.base_line = (-?\d+),", contents)
            if base_line is None:
                raise RuntimeError(f"generated {size}px LVGL font lacks a base line")
            generated_c[size] = contents
            fonts.append(
                {
                    "size_px": size,
                    "line_height_px": line_height_px,
                    "path": f"assets/fonts/lvgl/micro_ui_sans_{size}.c",
                    "payload_bytes": payload_bytes,
                    "sha256": hashlib.sha256(contents).hexdigest(),
                }
            )

            ipa_c_font = temporary_directory / f"micro_ui_ipa_{size}.c"
            ipa_bin_font = temporary_directory / f"micro_ui_ipa_{size}.bin"
            generate_lvgl_font(
                IPA_SOURCE_PATH,
                size,
                ipa_c_font,
                ipa_bin_font,
                ipa_glyphs_text,
                f"micro_ui_ipa_{size}",
            )
            if not lvgl_font_contains(ipa_c_font.read_text(), 0x0259):
                raise RuntimeError(f"generated {size}px IPA LVGL font lacks U+0259")
            ipa_payload_bytes = ipa_bin_font.stat().st_size
            ipa_contents = normalize_lvgl_c(
                ipa_c_font.read_bytes(),
                ipa_payload_bytes,
                line_height_px,
                symbol_prefix="micro_ui_ipa",
                export_macro="MICRO_UI_IPA_EXPORT",
                source_label=(
                    "NotoSans-Regular.otf "
                    "(pinned in assets/fonts/noto-sans-sc.json)"
                ),
                base_line_px=int(base_line.group(1)),
            )
            generated_ipa_c[size] = ipa_contents
            ipa_fonts.append(
                {
                    "size_px": size,
                    "line_height_px": line_height_px,
                    "path": f"assets/fonts/lvgl/micro_ui_ipa_{size}.c",
                    "payload_bytes": ipa_payload_bytes,
                    "sha256": hashlib.sha256(ipa_contents).hexdigest(),
                }
            )

        primary_payload_bytes = sum(int(font["payload_bytes"]) for font in fonts)
        ipa_payload_bytes = sum(int(font["payload_bytes"]) for font in ipa_fonts)
        declaration = {
            "source_sha256": metadata["source_sha256"],
            "bpp": LVGL_BPP,
            "fonts": fonts,
            "ipa": {
                "source_sha256": metadata["ipa"]["source_sha256"],
                "bpp": LVGL_BPP,
                "fonts": ipa_fonts,
                "total_payload_bytes": ipa_payload_bytes,
                "web": {
                    "path": IPA_WEB_FONT_PATH.relative_to(REPOSITORY_ROOT).as_posix(),
                    "sha256": sha256(ipa_web_font),
                },
            },
            "total_payload_bytes": primary_payload_bytes + ipa_payload_bytes,
            "web": {
                "path": WEB_FONT_PATH.relative_to(REPOSITORY_ROOT).as_posix(),
                "sha256": sha256(web_font),
            },
        }
        declaration_bytes = (json.dumps(declaration, indent=2) + "\n").encode()

        expected = {
            WEB_FONT_PATH: web_font.read_bytes(),
            IPA_WEB_FONT_PATH: ipa_web_font.read_bytes(),
            LVGL_SIZES_PATH: declaration_bytes,
            **{
                LVGL_DIRECTORY / f"micro_ui_sans_{size}.c": contents
                for size, contents in generated_c.items()
            },
            **{
                LVGL_DIRECTORY / f"micro_ui_ipa_{size}.c": contents
                for size, contents in generated_ipa_c.items()
            },
        }
        if check:
            mismatches = [
                path.relative_to(REPOSITORY_ROOT).as_posix()
                for path, contents in expected.items()
                if not path.is_file() or path.read_bytes() != contents
            ]
            if mismatches:
                raise SystemExit(
                    "generated font assets differ: " + ", ".join(mismatches)
                )
            return

        WEB_FONT_PATH.parent.mkdir(parents=True, exist_ok=True)
        LVGL_DIRECTORY.mkdir(parents=True, exist_ok=True)
        for path, contents in expected.items():
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(contents)


def parse_arguments() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    subparsers = parser.add_subparsers(dest="command", required=True)
    for command in ("manifest", "fonts"):
        subparser = subparsers.add_parser(command)
        subparser.add_argument(
            "--check", action="store_true", help="compare tracked output without rewriting"
        )
    return parser.parse_args()


def main() -> None:
    arguments = parse_arguments()
    if arguments.command == "manifest":
        generate_manifest(arguments.check)
    else:
        generate_fonts(arguments.check)


if __name__ == "__main__":
    main()
